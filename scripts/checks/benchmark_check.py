"""The brewery stream table against published plant benchmarks (step 1).

Usage:
    python -m scripts.checks.benchmark_check cases/brewery.json

No measured data from a real plant are available to this project. This check compares the generalised
brewery of Padullés et al. (2026) with two independent published sources (data/sources/brewery_benchmarks.csv):

* EU Food, Drink and Milk Industries BREF (JRC, 2019): brewhouse heat per hl (Table 4.1, literature and
  measured ranges; Table 4.3, an infusion-mashing brewery), whole-site heat (Table 4.3), the indicative BAT
  level of specific energy use (Table 17.5) and the boiling duration (Sec. 4.2.1.6);
* TNO process and waste heat dataset (Marina et al. 2021), product "Beer": ratio of waste heat to process heat
  and the temperature levels of each.

Verdicts (pinned in tests/test_reproductions.py):
    B1 brewhouse heat demand before recovery (pre-mashing to wort boiling) lies within the BREF measured range;
    B2 the existing network's hot utility is below the whole-site heat of the BREF infusion brewery (which also
       covers packaging, not in the stream table).
The TNO comparison is reported, not judged: its process heat is the plants' hot utility and its waste heat
what they reject, i.e. after their own heat recovery, as for the existing network N0 here.
Writes outputs/<case>/benchmark_check.md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from pinch import load_streams
from pinch.case import load_case

ROOT = Path(__file__).resolve().parents[2]   # repository root
BREWHOUSE = ("Pre-mashing", "Mashing", "Lautering/Filtering", "Wortboiling (preheating)", "Wortboiling (boiling)")


def checks(case_file: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(comparison table, verdicts) for the brewery case."""
    case = load_case(case_file)
    streams = load_streams(case.stream_file)
    bench = pd.read_csv(ROOT / "data" / "sources" / "brewery_benchmarks.csv", comment="#")
    summary = json.loads((ROOT / "outputs" / case.name / "summary.json").read_text(encoding="utf-8"))
    n0 = summary["retrofit"]["networks"][case.retrofit["baseline"]]
    brewhouse = sum(s.Q for s in streams.cold if s.name in BREWHOUSE)
    site_demand = sum(s.Q for s in streams.cold)

    def row(item: str) -> pd.Series:
        return bench[bench["item"] == item].iloc[0]

    measured = row("Table 4.1 brewhouse heat (measured)")
    literature = row("Table 4.1 brewhouse heat (literature)")
    infusion = row("Table 4.3 brewhouse wort preparation heat (infusion mashing)")
    site = row("Table 4.3 whole-site heat (same brewery)")
    bat = row("Table 17.5 indicative BAT level (yearly average)")
    tno = bench[bench["source"] == "TNO"]
    tno_ratio = tno.loc[tno["quantity"] == "waste_heat_TJ", "mean"].sum() / tno.loc[tno["quantity"] == "process_heat_TJ", "mean"].sum()
    table = pd.DataFrame([
        {"quantity": "Brewhouse heat demand before recovery [kWh/hl]", "case": round(brewhouse, 2),
         "benchmark": f"{measured['low']:g}-{measured['high']:g} measured; {literature['low']:g}-{literature['high']:g} literature",
         "source": "FDM BREF Table 4.1"},
        {"quantity": "Existing network hot utility, whole stream table [kWh/hl]", "case": n0["Qh"],
         "benchmark": f"{infusion['mean']:g} brewhouse only; {site['mean']:g} whole site", "source": "FDM BREF Table 4.3"},
        {"quantity": "Heat demand of all cold streams [kWh/hl]", "case": round(site_demand, 2),
         "benchmark": f"BAT {bat['low']:g}-{bat['high']:g} (heat and electricity, whole site)", "source": "FDM BREF Table 17.5"},
        {"quantity": "Waste heat / process heat (existing network: Q̇c / Q̇h)", "case": round(n0["Qc"] / n0["Qh"], 3),
         "benchmark": f"{tno_ratio:.3f} (EU-28 beer, 15-200 °C)", "source": "TNO dataset (Marina et al. 2021)"},
    ])
    verdicts = pd.DataFrame([
        {"verdict": "B1", "passed": bool(measured["low"] <= brewhouse <= measured["high"]),
         "detail": f"{brewhouse:.2f} kWh/hl within {measured['low']:g}-{measured['high']:g}"},
        {"verdict": "B2", "passed": bool(n0["Qh"] < site["mean"]),
         "detail": f"{n0['Qh']:g} < {site['mean']:g} kWh/hl (BREF site figure includes packaging)"},
    ])
    return table, verdicts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("case", type=Path)
    args = parser.parse_args()
    case = load_case(args.case)
    table, verdicts = checks(args.case)
    lines = ["# Brewery stream table against published benchmarks", "",
             "No measured plant data are available; these are plausibility checks against independent published "
             "figures (`data/sources/brewery_benchmarks.csv`). Generated by `scripts/checks/benchmark_check.py`.", "",
             "| Quantity | Case | Benchmark | Source |", "|---|---|---|---|"]
    lines += [f"| {r.quantity} | {r.case:g} | {r.benchmark} | {r.source} |" for r in table.itertuples()]
    lines += ["", "The stream table covers the brewhouse, fermentation, cooling and CIP; bottling, kegging, pasteurising "
              "and room heating are not in it, so whole-site figures are upper references.", "",
              "## Verdicts", "", "| Verdict | Passed | Detail |", "|---|---|---|"]
    lines += [f"| {v.verdict} | {'yes' if v.passed else 'NO'} | {v.detail} |" for v in verdicts.itertuples()]
    (ROOT / "outputs" / case.name / "benchmark_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{case.name}: {int(verdicts['passed'].sum())} of {len(verdicts)} verdicts pass")


if __name__ == "__main__":
    main()
